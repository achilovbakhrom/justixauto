const fail = (message) => { throw new Error(message); };
const object = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const sorted = (v) => Object.keys(v).sort();
const stable = (v) => JSON.stringify(v, (_, item) => object(item)
  ? Object.fromEntries(sorted(item).map((key) => [key, item[key]])) : item);
function keys(value, allowed, where) {
  if (!object(value)) fail(`${where}: expected object`);
  for (const key of sorted(value)) if (!allowed.includes(key)) fail(`${where}: unsupported ${key}`);
}
function readJSON(path) {
  // JSON.parse alone silently accepts duplicate object keys. Walk tokens first.
  const text = new TextDecoder('utf-8', {fatal:true}).decode(readFileSync(path));
  let i = 0;
  function ws() { while (/[\t\n\r ]/.test(text[i] ?? '\0')) i++; }
  function string() {
    const start = i++;
    while (i < text.length) {
      if (text[i] === '\\') { i += 2; continue; }
      if (text[i++] === '"') return JSON.parse(text.slice(start, i));
    }
    fail('unterminated JSON string');
  }
  function value() {
    ws();
    if (text[i] === '"') { string(); return; }
    if (text[i] === '{' || text[i] === '[') {
      const isObject = text[i++] === '{', end = isObject ? '}' : ']';
      const seen = new Set(); ws();
      if (text[i] === end) { i++; return; }
      while (i < text.length) {
        if (isObject) {
          ws(); if (text[i] !== '"') fail('JSON-form OpenAPI/config required');
          const key = string(); if (seen.has(key)) fail('duplicate JSON key'); seen.add(key);
          ws(); if (text[i++] !== ':') fail('invalid JSON object');
        }
        value(); ws(); if (text[i] === end) { i++; return; }
        if (text[i++] !== ',') fail('invalid JSON separator');
      }
      fail('unterminated JSON container');
    }
    const token = /^(?:true|false|null|-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?)/.exec(text.slice(i));
    if (!token) fail('JSON-form OpenAPI/config required (general YAML is unsupported)');
    i += token[0].length;
  }
  value(); ws(); if (i !== text.length) fail('invalid trailing JSON');
  return JSON.parse(text);
}
const refName = (s) => {
  const match = /^#\/components\/schemas\/([A-Z][A-Za-z0-9]*)$/.exec(s.$ref ?? '');
  if (!match) fail('only local named schema references are supported');
  return match[1];
};
const baseType = (s) => Array.isArray(s.type) ? s.type.find((t) => t !== 'null') : s.type;
const nullable = (s) => Array.isArray(s.type) && s.type.includes('null');
const goName = (s) => s.replace(/(^|_)([A-Za-z])/g, (_, __, c) => c.toUpperCase());
const tsImports = ['ApiRequest', 'ApiResult'];
