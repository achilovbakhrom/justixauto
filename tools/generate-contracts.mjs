function goType(s) {
  if (s.$ref) return refName(s);
  let type;
  switch (baseType(s)) {
    case 'string': type = 'string'; break;
    case 'integer': type = 'int64'; break;
    case 'boolean': type = 'bool'; break;
    case 'null': return '*struct{}';
    case 'array': type = `[]${goType(s.items)}`; break;
    case 'object': type = s.additionalProperties === false
      ? `struct {\n${sorted(s.properties).map((k) => `${goName(k.replaceAll('-', '_'))} ${s.required?.includes(k) ? goType(s.properties[k]) : `ContractOptional[${goType(s.properties[k])}]`} \`json:"${k}${s.required?.includes(k) ? '' : ',omitzero'}"\``).join('\n')}\n}`
      : `map[string]${goType(s.additionalProperties)}`; break;
    default: fail('union must be a named component');
  }
  return nullable(s) ? `*${type}` : type;
}

