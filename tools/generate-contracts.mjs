#!/usr/bin/env node
/**
 * T-640, profile 1. JSON-form OpenAPI 3.1 only; no dependency downloads.
 * Usage: node tools/generate-contracts.mjs [--config file.json] [--check]
 * Config: {version:1,contracts:[{input,goOutput,tsOutput,goPackage,owner,namespace}]}.
 * Paths are relative to the config. Outputs must already carry our header before
 * replacement. All inputs are validated/rendered before any output is changed.
 * Empty configuration fails: it is not evidence of real contract regeneration.
 *
 * Supported: local acyclic schema refs; closed objects; typed maps (without
 * fixed properties); arrays; strings, booleans, null, bounded safe integers;
 * nullable type pairs; primitive const/enum; component oneOf of component refs;
 * min/max length/items, uniqueItems, numeric bounds, UUID/date/UTC date-time;
 * portable ASCII regular expressions (no lookarounds/backrefs/flags).
 * Unknown keywords fail, including allOf/anyOf, nullable, defaults, coercion,
 * external refs, number/int64-number, arbitrary maps and discriminator.
 * Public owner routes, path/query scalar parameters and T-032's three dedicated
 * revision/idempotency headers are supported. Success schemas must be identical
 * across selected statuses (T-032's schema adapter cannot inspect status).
 * Strict end-of-input pattern suffix `(?![\\s\\S])` is supported explicitly;
 * ordinary `$` retains its JSON Schema/ECMAScript non-multiline semantics.
 * Internal owner routes are Go-only and require declared mutualTLS security.
 * Public cookie security declarations are preserved as endpoint metadata;
 * browser credentials remain under T-032 and authorization remains server-side.
 * Response headers, 429, cookie parameters and other HTTP features
 * require an explicit transport/profile handoff. No network transport is emitted:
 * TS delegates to T-032; Go consumes an injected owner exchange port.
 */
